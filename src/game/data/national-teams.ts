/** 国家队球员：位置/风格 + 相对全队平均的偏移（核心 +3，主力 0，替补 -3）。 */
type NationalPlayerTuple = [name: string, enName: string, pos: Position, style: StyleId, offset: number, foot?: Foot]

type NationalTeamOptions = {
  id: string
  country: string
  countryEn: string
  year: string
  coach: string
  /** 该队的目标首发平均 CA；用来换算 7 项主属性的平均目标。 */
  ca: number
  formationId: ElevenFormationId
  tactics: Tactics
  color: string
  accent: string
  note: string
}

function nationalTeam(options: NationalTeamOptions, players: NationalPlayerTuple[]): LegendTeamDef {
  const baseAvg = Math.max(45, Math.min(100, Math.round(100 * Math.sqrt(options.ca / 1500))))
  return {
    id: options.id,
    club: options.country,
    clubEn: options.countryEn,
    season: options.year,
    coach: options.coach,
    tier: options.ca >= 1200 ? 'S+' : options.ca >= 1100 ? 'S' : 'A',
    formationId: options.formationId,
    tactics: options.tactics,
    color: options.color,
    accent: options.accent,
    note: options.note,
    players: players.map(([name, enName, pos, style, offset, foot]) => [
      name,
      enName,
      options.country,
      pos,
      style,
      Math.max(40, Math.min(100, baseAvg + offset)),
      foot ?? 'R',
    ]) as LegendPlayerTuple[],
  }
}

